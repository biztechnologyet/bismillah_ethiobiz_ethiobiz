def split_bilingual(value):
    """Split legacy ``English | አማርኛ`` values into a pair."""
    if not value:
        return "", ""
    text = str(value)
    if " | " in text:
        english, amharic = text.split(" | ", 1)
        return english.strip(), amharic.strip()
    return text.strip(), ""


def subsystem_for_url(url):
    lowered = (url or "").strip().lower()
    for prefix, key in URL_SUBSYSTEM_RULES:
        if lowered.startswith(prefix):
            return key
    return "none"
